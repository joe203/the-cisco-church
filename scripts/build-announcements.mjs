// Turn the weekly announcements PDF (exported from PowerPoint) into the
// images + manifest behind /announcements, and keep the last few weeks.
//
//   node scripts/build-announcements.mjs "<file.pdf>" --date 2026-11-01 --skip 1
//
// --date  the Sunday these announcements are for (the page says "For Sunday …")
// --skip  page numbers to leave off the public page (default: none). Page 1,
//         "We're glad you're here", is skipped because the page header has its own.
//
// Needs `pdftoppm` (poppler) on PATH. Writes public/announcements/<date>/NN.webp
// and lib/announcements/<date>.json (title / alt / details start blank — fill
// them in; mark the prayer-request slide `"currentOnly": true` so it drops off
// once the week is no longer current). Then it keeps the newest week plus the
// three before it and deletes older ones, and rewrites lib/announcements/weeks.ts.
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import sharp from "../node_modules/sharp/dist/index.mjs";

const KEEP_EARLIER = 3;

const args = process.argv.slice(2);
const pdf = args[0];
const flag = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const date = flag("date");
const skip = new Set((flag("skip") ?? "").split(",").filter(Boolean).map(Number));

if (!pdf || pdf.startsWith("--") || !date || !/^\d{4}-\d{2}-\d{2}$/.test(date)) {
  console.error('usage: node scripts/build-announcements.mjs "<file.pdf>" --date yyyy-mm-dd [--skip 1,6,8]');
  process.exit(1);
}

const tmp = mkdtempSync(path.join(os.tmpdir(), "announce-"));
// 144 dpi on a 960x540pt slide = 1920x1080.
execFileSync("pdftoppm", ["-r", "144", "-png", pdf, path.join(tmp, "p")]);
const pages = readdirSync(tmp)
  .filter((f) => f.endsWith(".png"))
  .sort((a, b) => parseInt(a.match(/(\d+)/)[1]) - parseInt(b.match(/(\d+)/)[1]));

const outDir = path.join("public", "announcements", date);
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const slides = [];
for (let i = 0; i < pages.length; i++) {
  if (skip.has(i + 1)) continue;
  const name = `${String(slides.length + 1).padStart(2, "0")}.webp`;
  await sharp(path.join(tmp, pages[i])).resize({ width: 1920 }).webp({ quality: 82 }).toFile(path.join(outDir, name));
  slides.push({ id: `slide-${slides.length + 1}`, file: name, title: "", alt: "", details: [] });
}
rmSync(tmp, { recursive: true, force: true });

mkdirSync(path.join("lib", "announcements"), { recursive: true });
writeFileSync(path.join("lib", "announcements", `${date}.json`), JSON.stringify({ date, slides }, null, 2) + "\n");

// Keep the newest week and the KEEP_EARLIER before it.
const weeks = readdirSync(path.join("lib", "announcements"))
  .filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f))
  .map((f) => f.replace(".json", ""))
  .sort()
  .reverse();
for (const old of weeks.slice(KEEP_EARLIER + 1)) {
  rmSync(path.join("lib", "announcements", `${old}.json`), { force: true });
  rmSync(path.join("public", "announcements", old), { recursive: true, force: true });
  console.log(`Removed old week ${old}`);
}
const kept = weeks.slice(0, KEEP_EARLIER + 1).filter((w) => existsSync(path.join("lib", "announcements", `${w}.json`)));

const ident = (w) => `w${w.replace(/-/g, "")}`;
writeFileSync(
  path.join("lib", "announcements", "weeks.ts"),
  `// Generated by scripts/build-announcements.mjs — newest week first.\n` +
    kept.map((w) => `import ${ident(w)} from "./${w}.json";`).join("\n") +
    `\n\nexport const rawWeeks = [${kept.map(ident).join(", ")}];\n`,
);

console.log(`Wrote ${slides.length} slides for ${date} (skipped ${[...skip].join(", ") || "none"}). Kept weeks: ${kept.join(", ")}.`);
console.log("Now fill in title/alt/details in lib/announcements/" + date + ".json.");
