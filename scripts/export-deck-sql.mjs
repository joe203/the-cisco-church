// Export a seed deck from lib/seed.ts to an idempotent SQL migration.
// Node 22+ runs the TypeScript import directly via type stripping.
//
//   node scripts/export-deck-sql.mjs <deck-slug> <deck-uuid> [> out.sql]
//
// Example:
//   node scripts/export-deck-sql.mjs open-water-faith \
//     c1000000-0000-4000-8000-000000000003 \
//     > supabase/migrations/004_open_water_faith.sql

import { seedDecks } from "../lib/seed.ts";

const [slug, uuid] = process.argv.slice(2);
if (!slug || !uuid) {
  console.error("usage: node scripts/export-deck-sql.mjs <deck-slug> <deck-uuid>");
  process.exit(1);
}

const deck = seedDecks.find((d) => d.slug === slug);
if (!deck) {
  console.error(`Unknown deck slug: ${slug}`);
  process.exit(1);
}

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const lines = [];
lines.push(`-- Generated by scripts/export-deck-sql.mjs from lib/seed.ts — deck "${deck.slug}".`);
lines.push(`-- Idempotent via fixed UUID and ON CONFLICT DO NOTHING.`);
lines.push(``);
lines.push(`begin;`);
lines.push(``);
lines.push(`insert into cisco.cisco_decks (id, slug, title, sermon_id, metadata)`);
lines.push(
  `values (${q(uuid)}, ${q(deck.slug)}, ${q(deck.title)}, null, ${q(
    JSON.stringify({ backgrounds: deck.backgrounds }),
  )}::jsonb)`,
);
lines.push(`on conflict (slug) do nothing;`);
lines.push(``);
lines.push(`insert into cisco.cisco_slides (deck_id, position, html, outline_html, bg, notes)`);
lines.push(`values`);
lines.push(
  deck.slidesWithNotes
    .map(
      (s) =>
        `  (${q(uuid)}, ${s.position}, ${q(s.html)}, ${q(s.outline_html)}, ${q(s.bg)}, ${q(s.notes)})`,
    )
    .join(",\n"),
);
lines.push(`on conflict (deck_id, position) do nothing;`);
lines.push(``);
lines.push(`insert into cisco.cisco_deck_state (deck_id, current_slide, is_live, is_blank)`);
lines.push(`values (${q(uuid)}, 1, false, false)`);
lines.push(`on conflict (deck_id) do nothing;`);
lines.push(``);
lines.push(`commit;`);

process.stdout.write(lines.join("\n") + "\n");
